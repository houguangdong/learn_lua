#!/usr/local/bin/lua

--next 是 Lua 的內建函數，用來遍歷 table 的鍵值對（key-value pairs），它是 pairs() 背後真正的核心迭代器。
--基本用法
--next(table [, index])
--
--第一個參數：要遍歷的 table
--第二個參數：當前的 key（可以是 nil）
--返回值：下一個 key 和 對應的 value（兩個返回值）
--
--當你傳入 nil 作為第二個參數時，會返回 table 中的「第一個」鍵值對（順序不定）。
--當 table 已經遍歷完畢時，next 會返回 nil。

print('---------------------------------------------------------------------------------------------------------------')
--1. 最常见的几种写法对比
local t = {a = 10, b=20, [false]="bool", xyz=30, [100]=99}

-- 写法1：最常用（推荐）
for k, v in pairs(t) do
    print(k, v)
end
print('---------------------------------------------------------------------------------------------------------------')
-- 写法2：完全等价于上面（pairs 的本质）
for k, v in next, t do
    print(k, v)
end
print('---------------------------------------------------------------------------------------------------------------')
-- 写法3：显式写出初始 nil（最清晰理解 next 的用法）
for k, v in next, t, nil do
    print(k, v)
end
print('---------------------------------------------------------------------------------------------------------------')
-- 写法4：手动控制（最能看懂 next 的工作原理）
local k = nil
repeat
    k, v = next(t, k)
    if k ~= nil then
        print(k, v)
    end
until k == nil
print('---------------------------------------------------------------------------------------------------------------')
--2. next() 的核心规则（一定要记住）
--调用方式,                         返回值含义,                               什么时候出现
--next(t),                        "等价于 next(t, nil)",                   常用来判断空表
--"next(t, nil)",                 返回「第一个」键值对（顺序不定）,             开始遍历
--"next(t, 某个已存在的key)",        返回「下一个」键值对,                      继续遍历
--"next(t, 最后一个key)",           返回 nil,                               遍历结束
--"next(t, 不存在的key)",           通常返回 nil（除非那个key刚好是最后一个）,     —

--3. 经典用法速查表
