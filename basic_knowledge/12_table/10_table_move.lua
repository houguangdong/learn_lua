--含义：把 TransactionParams 表的所有元素完整追加到 params 表的末尾。
--这是一种非常常见的用法——合并两个参数列表或事务参数列表。
--
--
--总结：
--table.move 是 Lua 中高效处理表元素批量移动/复制的工具，尤其适合数组型表（连续整数索引）。
--推荐在需要追加大量元素、表内整体平移、或实现高效合并时使用它。