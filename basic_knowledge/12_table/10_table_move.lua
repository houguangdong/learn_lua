#!/usr/local/bin/lua

--Lua 中 table.move 的使用方法（Lua 5.3 及以上版本引入）
--函数语法
--Luatable.move(a1, f, e, t [, a2])
--参数说明（中文解释）：
--    a1：源表（要从中复制/移动元素的表）
--    f：源表中开始索引（必须是正整数，通常从 1 开始）
--    e：源表中结束索引（包含这个位置）
--    t：目标起始位置（元素会从这个位置开始放入目标表）
--    a2：目标表（可选，默认是 a1 自身）
--
--功能：
--将源表 a1 中从索引 f 到 e 的元素，复制（或移动）到目标表 a2 中，从索引 t 开始的位置存放。
--它相当于执行一系列赋值操作：a2[t] = a1[f], a2[t+1] = a1[f+1], ..., a2[t + (e-f)] = a1[e]。
--注意事项：
--
--如果不传 a2，则在同一个表内移动元素（支持重叠区域，类似内存移动）。
--如果传了 a2，则是在两个不同的表之间复制元素（源表不会被清空）。
--常用于批量追加元素、表内元素整体移动、删除中间元素后前移等场景。
--效率比手写 for 循环更高（底层用 C 实现）。
--
--简单例子 1：两个表之间复制（追加元素）
local src = {10, 20, 30, 40}      -- 源表
local dest = {1, 2, 3}            -- 目标表

-- 把 src 的全部元素追加到 dest 的末尾
table.move(src, 1, #src, #dest + 1, dest)

print(table.concat(dest, ", "))   -- 输出: 1, 2, 3, 10, 20, 30, 40

--解释：
--#src 是源表长度（4），#dest + 1 是目标表的下一个空位置（4），所以把 src[1..4] 复制到 dest[4..7]。
--简单例子 2：在同一个表内移动元素（整体前移或后移）
local t = { "a", "b", "c", "d", "e" }

-- 把索引 3 到 5 的元素移动到索引 1 开始的位置（覆盖前面）
table.move(t, 3, 5, 1)

print(table.concat(t, ", "))   -- 输出: c, d, e, d, e
--解释：
--原表：1=a, 2=b, 3=c, 4=d, 5=e
--移动后：1=c, 2=d, 3=e, 4=d, 5=e（后面元素被覆盖）


--实用例子 3：删除中间元素后，前面的元素自动前移
local t = { "苹果", "香蕉", "橙子", "葡萄", "西瓜" }
-- 删除索引 3 的 "橙子"，并把后面的元素往前移动
table.remove(t, 3)              -- 先移除
-- 或者用 move 实现批量前移（更灵活）
table.move(t, 4, #t, 3)         -- 把原4到末尾移动到位置3开始

print(table.concat(t, ", "))    -- 输出: 苹果, 香蕉, 葡萄, 西瓜


--实用例子 4：复制部分元素到新表
local params = { "name", "age" }
local extra = { "city", "country", "phone" }

-- 只把 extra 的第 2 到 3 个元素追加到 params
table.move(extra, 2, 3, #params + 1, params)

print(table.concat(params, ", "))   -- 输出: name, age, country, phone
